/**
 * Content audit: the "Grandma test" and the tone rules, checked by machine.
 * Run with `npm run audit`. Writes docs/content-audit.md and fails (exit 1)
 * if a hard rule is broken.
 *
 * Hard rules (fail):
 *   - each lesson, and the glossary as a whole, scores 70+ for reading ease
 *   - no sentence longer than 25 words in lessons or glossary
 *   - no paragraph longer than 3 sentences
 *   - no banned word (buzzwords, hype, fear)
 *   - every glossary analogy says where the comparison stops working
 * Soft rules (reported): sentences of 21-25 words, single entries scoring under 60.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { isFullLesson } from '../src/content/lessons.ts';
import { type Language, LONG_SENTENCE, bannedHits, measure, sentenceCount } from '../src/content/readability.ts';
import { LocaleContentSchema, type LocaleContent } from '../src/content/schema.ts';
import { CONTENT_DIR, listLocales, loadLocale } from './content-lib.ts';

const TARGET = 70;
const HARD_SENTENCE = 25;
const MAX_PARAGRAPH_SENTENCES = 3;
/** Words that show an analogy admits its limit. */
const LIMIT_WORDS: Record<Language, RegExp> = {
  en: /\b(unlike|but|still|however|neither|nobody)\b/i,
  fr: /\b(contrairement|mais|pourtant|aucun|nul|personne)\b/i,
};

type Group = { name: string; blocks: string[]; paragraphs: string[] };

/** The prose of the app, grouped the way a reader meets it. Prompts to copy are not prose and are left out. */
function groups(c: LocaleContent): { lessons: Group[]; terms: Group[]; other: Group[] } {
  const lessons = c.lessons.filter(isFullLesson).map((l) => {
    const paragraphs = [
      l.opener,
      ...l.idea.paragraphs,
      l.idea.simpler,
      l.idea.analogy,
      l.idea.analogyLimit,
      ...l.sections.flatMap((s) => s.paragraphs),
      ...l.example.paragraphs,
      ...l.tryIt,
      ...l.quickCheck.flatMap((q) => q.options.map((o) => o.reply)),
    ];
    const short = [...l.takeaways, ...l.quickCheck.flatMap((q) => [q.question, ...q.options.map((o) => o.text)])];
    return { name: l.id, blocks: [...paragraphs, ...short], paragraphs };
  });
  const terms = c.glossary.map((t) => ({
    name: t.id,
    blocks: [t.definition, t.simpler, t.analogy, t.example, ...(t.usageNote ? [t.usageNote] : [])],
    paragraphs: [t.definition, t.simpler, t.example],
  }));
  const k = c.toolkit;
  const other: Group[] = [
    { name: 'pages', blocks: [...c.pages.why.paragraphs, c.pages.plan.intro, ...c.pages.plan.steps.map((s) => s.text)], paragraphs: c.pages.why.paragraphs },
    { name: 'toolkit: recipe', blocks: [k.recipe.intro, k.recipe.note, ...k.recipe.elements.flatMap((e) => [e.oneLine, e.analogy, e.helper])], paragraphs: [k.recipe.note] },
    { name: 'toolkit: checklist', blocks: k.checklist.flatMap((i) => [i.question, i.suggestion]), paragraphs: [] },
    { name: 'toolkit: tips', blocks: k.tips.flatMap((t) => [t.text, t.example]), paragraphs: k.tips.map((t) => t.text) },
    { name: 'toolkit: gallery notes', blocks: k.gallery.map((g) => g.why), paragraphs: k.gallery.map((g) => g.why) },
    { name: 'toolkit: template notes', blocks: k.templates.map((t) => t.use), paragraphs: [] },
    { name: 'exercises', blocks: c.exercises.flatMap((e) => [e.goal, ...e.good, e.better.text, ...e.selfCheck]), paragraphs: c.exercises.flatMap((e) => e.good) },
  ];
  return { lessons, terms, other };
}

const fmt = (n: number) => n.toFixed(1);
const out: string[] = ['# Content audit', '', `Generated by \`npm run audit\` on ${new Date().toISOString().slice(0, 10)}.`, ''];
const failures: string[] = [];
const fail = (msg: string) => failures.push(msg);

for (const code of listLocales()) {
  const lang = code as Language;
  const content = LocaleContentSchema.parse(loadLocale(code));
  const g = groups(content);
  const formula = lang === 'en' ? 'Flesch Reading Ease' : 'Kandel-Moles (French Flesch)';
  out.push(`## ${content.meta.name} (${code})`, '', `Formula: ${formula}. Target: ${TARGET} or more. Higher is easier.`, '');

  // ---- Lessons ----
  out.push('### Lessons', '', '| Lesson | Score | Words | Words per sentence | Sentences over 20 words |', '|---|---|---|---|---|');
  for (const lesson of g.lessons) {
    const r = measure(lesson.blocks, lang);
    out.push(`| ${lesson.name} | ${fmt(r.score)} | ${r.words} | ${fmt(r.wordsPerSentence)} | ${r.longSentences.length} |`);
    if (r.score < TARGET) fail(`[${code}] lesson "${lesson.name}" scores ${fmt(r.score)} (target ${TARGET})`);
  }
  out.push('');

  // ---- Glossary ----
  const all = measure(g.terms.flatMap((t) => t.blocks), lang);
  out.push('### Glossary', '', `${g.terms.length} terms. Overall score: **${fmt(all.score)}**, ${fmt(all.wordsPerSentence)} words per sentence.`, '');
  if (all.score < TARGET) fail(`[${code}] glossary scores ${fmt(all.score)} overall (target ${TARGET})`);
  const hard = g.terms.map((t) => ({ name: t.name, r: measure(t.blocks, lang) })).filter((t) => t.r.score < 60);
  if (hard.length) {
    out.push('Entries under 60 (usually because the term itself is a long word):', '');
    for (const t of hard.sort((a, b) => a.r.score - b.r.score)) out.push(`- ${t.name}: ${fmt(t.r.score)}`);
    out.push('');
  }
  for (const term of content.glossary) {
    if (!LIMIT_WORDS[lang].test(term.analogy)) fail(`[${code}] term "${term.id}": the analogy does not say where it stops working`);
  }

  // ---- Everything else ----
  out.push('### Toolkit, exercises and pages', '', '| Section | Score | Words per sentence |', '|---|---|---|');
  for (const group of g.other) {
    const r = measure(group.blocks, lang);
    out.push(`| ${group.name} | ${fmt(r.score)} | ${fmt(r.wordsPerSentence)} |`);
    if (r.score < TARGET) fail(`[${code}] ${group.name} scores ${fmt(r.score)} (target ${TARGET})`);
  }
  out.push('');

  // ---- Sentence and paragraph length, banned words ----
  const everything = [...g.lessons, ...g.terms, ...g.other];
  const long = everything.flatMap((grp) => measure(grp.blocks, lang).longSentences.map((s) => ({ ...s, where: grp.name })));
  const tooLong = long.filter((s) => s.words > HARD_SENTENCE);
  for (const s of tooLong) fail(`[${code}] ${s.where}: sentence of ${s.words} words: "${s.text}"`);
  out.push('### Sentence length', '', `Sentences over ${LONG_SENTENCE} words: ${long.length}. Over ${HARD_SENTENCE} words (not allowed): ${tooLong.length}.`, '');
  for (const s of long.sort((a, b) => b.words - a.words).slice(0, 12)) out.push(`- ${s.words} words, ${s.where}: "${s.text}"`);
  out.push('');

  let longParagraphs = 0;
  for (const grp of everything) {
    for (const p of grp.paragraphs) {
      const n = sentenceCount(p);
      if (n > MAX_PARAGRAPH_SENTENCES) {
        longParagraphs++;
        fail(`[${code}] ${grp.name}: paragraph of ${n} sentences: "${p.slice(0, 60)}..."`);
      }
    }
  }
  out.push('### Paragraph length', '', `Paragraphs over ${MAX_PARAGRAPH_SENTENCES} sentences: ${longParagraphs}.`, '');

  let banned = 0;
  for (const grp of everything) {
    for (const block of grp.blocks) {
      for (const hit of bannedHits(block, lang)) {
        banned++;
        fail(`[${code}] ${grp.name}: banned word or phrase "${hit}" in "${block.slice(0, 70)}..."`);
      }
    }
  }
  out.push('### Tone', '', `Buzzwords, hype or fear phrases found: ${banned}.`, '');
}

out.push('## Result', '', failures.length ? `**${failures.length} problem(s):**` : '**All checks passed.**', '');
for (const f of failures) out.push(`- ${f}`);

const docs = resolve(CONTENT_DIR, '..', 'docs');
mkdirSync(docs, { recursive: true });
writeFileSync(join(docs, 'content-audit.md'), out.join('\n') + '\n');
console.log(out.join('\n'));
if (failures.length) process.exit(1);
